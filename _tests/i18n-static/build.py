#!/usr/bin/env python3
"""Language URLs for search engines (owner, 17 Oct 2026).

For every page that has approved translations, writes one static page per language at <page>/<code>/index.html
(e.g. /id/, /campaigns/share-your-story/ta/), the same pattern as the Privacy Policy (/privacy/id/). Each copy:
  - is the English page with the APPROVED dictionary texts already filled in (the same dictionaries and the same
    rules as campaigns/shared/i18n-core.js apply in the browser; no wording is written here),
  - has html lang + data-static-lang, its own canonical and og:url, og:locale, translated title/description,
  - carries the full hreflang set (en, id, tl, my, bn, ta, zh-Hans, x-default), as do the English pages,
  - links to the same-language version of other translated pages.
The English pages only gain the hreflang block. The sitemap lists every language URL.

    python3 _tests/i18n-static/build.py          # write
    python3 _tests/i18n-static/build.py --check  # exit 1 if any generated file is missing or stale
Edit the dictionaries or the English page, never the generated copies; then run this again.
"""
import json
import os
import re
import subprocess
import sys
from urllib.parse import urlsplit, urlunsplit, urljoin

from bs4 import BeautifulSoup, NavigableString

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SITE = 'https://www.tulussg.com'
# Keep in step with STATIC_PAGES in campaigns/shared/i18n-core.js.
PAGES = ['/', '/campaigns/', '/campaigns/share-your-story/', '/campaigns/share-your-story-migrant-workers/',
         '/campaigns/sports-carnival/', '/domestic-worker-support-singapore/', '/migrant-worker-community-singapore/',
         '/caregiver-support-singapore/', '/community-resources-singapore/', '/faq/']
LANGS = ['en', 'id', 'tl', 'my', 'bn', 'ta', 'zh']
HTML_LANG = {'en': 'en', 'id': 'id', 'tl': 'fil', 'my': 'my', 'bn': 'bn', 'ta': 'ta', 'zh': 'zh-Hans'}
HREFLANG = {'en': 'en', 'id': 'id', 'tl': 'tl', 'my': 'my', 'bn': 'bn', 'ta': 'ta', 'zh': 'zh-Hans'}
OG_LOCALE = {'en': 'en_SG', 'id': 'id_ID', 'tl': 'tl_PH', 'my': 'my_MM', 'bn': 'bn_BD', 'ta': 'ta_SG', 'zh': 'zh_CN'}
PRIVACY = {'en': '/privacy/', 'id': '/privacy/id/', 'tl': '/privacy/tl/', 'my': '/privacy/my/', 'bn': '/privacy/bn/',
           'ta': '/privacy/ta/', 'zh': '/privacy/zh/'}
MARK_START = '<!-- language versions (generated by _tests/i18n-static/build.py) -->'
MARK_END = '<!-- /language versions -->'


def lang_path(path, code):
    """'/faq/' + 'id' -> '/faq/id/'; English -> the page itself. None if the page has no language versions."""
    if path not in PAGES:
        return None
    return path if code == 'en' else path + code + '/'


def dictionaries(page):
    out = subprocess.run(['node', os.path.join(ROOT, '_tests/i18n-static/dump-dicts.mjs'), page.lstrip('/') + 'index.html'],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def make_t(dicts, code):
    def lookup(c, key):
        for d in reversed(dicts):
            if isinstance(d.get(c), dict) and key in d[c]:
                return d[c][key]
        return None

    def t(key):
        v = lookup(code, key)
        if v is None:
            v = lookup('en', key)
        return key if v is None else v
    t.has_en = lambda key: lookup('en', key) is not None
    return t


def hreflang_block(path):
    lines = [MARK_START]
    for c in LANGS:
        lines.append('<link rel="alternate" hreflang="%s" href="%s%s">' % (HREFLANG[c], SITE, lang_path(path, c)))
    lines.append('<link rel="alternate" hreflang="x-default" href="%s%s">' % (SITE, path))
    lines.append(MARK_END)
    return lines


def render_rich(soup, el, text):
    """Same rules as renderRich() in i18n-core.js: [em] [strong] [br] [aN] with the element's own links."""
    links = [a for a in el.find_all('a')]
    templates = []
    for a in links:
        n = soup.new_tag('a')
        n.attrs = dict(a.attrs)
        templates.append(n)
    el.clear()
    stack = [el]
    pos = 0
    for m in re.finditer(r'\[(/?)(em|strong|br|a[1-9])\]', text):
        if m.start() > pos:
            stack[-1].append(NavigableString(text[pos:m.start()]))
        pos = m.end()
        tag = m.group(2)
        if tag == 'br':
            stack[-1].append(soup.new_tag('br'))
            continue
        if m.group(1) == '/':
            if len(stack) > 1:
                stack.pop()
            continue
        if tag[0] == 'a':
            i = int(tag[1:]) - 1
            node = soup.new_tag('a')
            if i < len(templates):
                node.attrs = dict(templates[i].attrs)
            else:
                node = soup.new_tag('span')
        else:
            node = soup.new_tag(tag)
        stack[-1].append(node)
        stack.append(node)
    if pos < len(text):
        stack[-1].append(NavigableString(text[pos:]))


def localise_href(value, page, code):
    """Relative URLs become absolute (the copy lives one folder deeper); links to translated pages get the
    same-language URL. External, mail, tel, data and pure-fragment links are untouched."""
    if not value or value.startswith(('#', 'mailto:', 'tel:', 'data:', 'javascript:')):
        return value
    parts = urlsplit(value)
    if parts.scheme or parts.netloc:
        if parts.netloc in ('www.tulussg.com', 'tulussg.com'):
            lp = lang_path(parts.path or '/', code)
            if lp:
                return urlunsplit((parts.scheme, parts.netloc, lp, '', parts.fragment))
        return value
    absolute = urljoin(page, value)
    p = urlsplit(absolute)
    q = '&'.join(x for x in p.query.split('&') if x and not x.startswith('lang='))
    lp = lang_path(p.path, code)
    return urlunsplit(('', '', lp or p.path, q, p.fragment))


def build_copy(page, src, code, t):
    soup = BeautifulSoup(src, 'html.parser')
    html = soup.html
    html['lang'] = HTML_LANG[code]
    html['data-static-lang'] = code

    for el in soup.select('[data-i18n]'):
        el.string = t(el['data-i18n'])
    for el in soup.select('[data-i18n-rich]'):
        render_rich(soup, el, t(el['data-i18n-rich']))
    for el in soup.select('[data-i18n-attr]'):
        for pair in el['data-i18n-attr'].split(';'):
            if ':' in pair:
                attr, key = pair.split(':', 1)
                el[attr] = t(key)
    for el in soup.select('[data-i18n-link]'):
        before, _, after = t(el['data-i18n-link']).partition('{link}')
        a = soup.new_tag('a', href=PRIVACY[code] + ('#' + el['data-privacy-anchor'] if el.get('data-privacy-anchor') else ''))
        a.string = t('privacy.link')
        el.clear()
        el.append(NavigableString(before))
        el.append(a)
        el.append(NavigableString(after))
    for el in soup.select('[data-privacy-link]'):
        anchor = el.get('data-privacy-link') or ''
        el['href'] = PRIVACY[code] + ('#' + anchor if anchor else '')
        el.string = t('privacy.link')

    # URLs: absolute, and same-language where a translated page exists.
    for el in soup.find_all(True):
        if el.name == 'link' and (el.get('rel') or [''])[0] in ('canonical', 'alternate'):
            continue
        for attr in ('href', 'src', 'poster'):
            if el.has_attr(attr):
                el[attr] = localise_href(el[attr], page, code)
        if el.has_attr('srcset'):
            el['srcset'] = ', '.join(' '.join([localise_href(p.strip().split(' ')[0], page, code)] + p.strip().split(' ')[1:])
                                     for p in el['srcset'].split(','))

    select = soup.find(id='lang-select')
    if select:
        for o in select.find_all('option'):
            if o.get('value') == code:
                o['selected'] = ''
            elif o.has_attr('selected'):
                del o['selected']

    head = soup.head
    title = t('meta.title')
    if title != 'meta.title' and head.title:
        head.title.string = title
    url = SITE + lang_path(page, code)
    for sel, attr, val in (('link[rel=canonical]', 'href', url), ('meta[property="og:url"]', 'content', url)):
        for el in head.select(sel):
            el[attr] = val
    if t.has_en('meta.description'):
        for sel in ('meta[name=description]', 'meta[property="og:description"]', 'meta[name="twitter:description"]'):
            for el in head.select(sel):
                el['content'] = t('meta.description')
    if title != 'meta.title':
        for sel in ('meta[property="og:title"]', 'meta[name="twitter:title"]'):
            for el in head.select(sel):
                el['content'] = title
    loc = head.select_one('meta[property="og:locale"]')
    if loc is None:
        loc = soup.new_tag('meta', property='og:locale')
        (head.select_one('meta[property="og:type"]') or head.title).insert_before(loc)
    loc['content'] = OG_LOCALE[code]

    out = str(soup)
    banner = ('<!-- Generated by _tests/i18n-static/build.py from %sindex.html and its approved dictionaries (%s). '
              'Do not edit; edit the English page or the dictionaries and run the build. -->\n' % (page.lstrip('/'), code))
    return out.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner, 1) if out.startswith('<!DOCTYPE html>') else banner + out


def with_hreflang(src, page):
    """English source page: insert (or refresh) the hreflang block after the canonical link, keeping its formatting."""
    nl = '\r\n' if '\r\n' in src else '\n'
    src = re.sub(re.escape(MARK_START) + r'.*?' + re.escape(MARK_END) + r'\r?\n', '', src, flags=re.S)
    m = re.search(r'<link rel="canonical"[^>]*>\r?\n', src)
    if not m:
        raise SystemExit('no canonical link in ' + page)
    block = nl.join(hreflang_block(page)) + nl
    return src[:m.end()] + block + src[m.end():]


def sitemap(src):
    nl = '\r\n' if '\r\n' in src else '\n'
    blocks = re.findall(r'[ \t]*<url>.*?</url>\r?\n', src, flags=re.S)
    head = src[:src.index(blocks[0])]
    tail = src[src.index(blocks[-1]) + len(blocks[-1]):]
    gen = re.compile(r'<loc>%s(.*/)(?:id|tl|my|bn|ta|zh)/</loc>' % re.escape(SITE))
    out = []
    for b in blocks:
        g = gen.search(b)
        if g and g.group(1) in PAGES:
            continue                     # a previously generated language entry; rebuilt below
        out.append(b)
        m = re.search(r'<loc>%s(/[^<]*)</loc>' % re.escape(SITE), b)
        if m and m.group(1) in PAGES:
            for c in LANGS[1:]:
                out.append(b.replace('<loc>%s%s</loc>' % (SITE, m.group(1)), '<loc>%s%s</loc>' % (SITE, lang_path(m.group(1), c))))
    return head + ''.join(out) + tail


def main():
    check = '--check' in sys.argv
    stale = []

    def emit(rel, content):
        path = os.path.join(ROOT, rel)
        old = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
        if old != content:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, 'w', encoding='utf-8', newline='').write(content)

    for page in PAGES:
        rel = page.lstrip('/') + 'index.html'
        src = open(os.path.join(ROOT, rel), encoding='utf-8', newline='').read()
        emit(rel, with_hreflang(src, page))
        src = with_hreflang(src, page)
        dicts = dictionaries(page)
        for code in LANGS[1:]:
            emit(page.lstrip('/') + code + '/index.html', build_copy(page, src, code, make_t(dicts, code)))
    sm = open(os.path.join(ROOT, 'sitemap.xml'), encoding='utf-8', newline='').read()
    emit('sitemap.xml', sitemap(sm))

    if check:
        if stale:
            print('Language pages out of date (run _tests/i18n-static/build.py):', *stale, sep='\n  ')
            sys.exit(1)
        print('Language pages up to date (%d pages x %d languages).' % (len(PAGES), len(LANGS) - 1))
    else:
        print('Wrote %d file(s).' % len(stale))


if __name__ == '__main__':
    main()
